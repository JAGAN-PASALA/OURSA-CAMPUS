#!/usr/bin/env python3
"""Static API route inventory for security review; does not replace runtime tests."""
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "backend"
ROUTE_METHODS = {"get", "post", "put", "patch", "delete", "options", "head"}
AUTH_NAMES = {"current_user", "admin_only", "teacher_only", "student_only", "platform_admin_only", "staff_only", "authenticated_user", "allocation_manager"}
PUBLIC_PATH_PREFIXES = ("/api/public/", "/api/legal/")
PUBLIC_EXACT = {"/api/health", "/api/ready", "/api/auth/login", "/api/auth/forgot-password", "/api/auth/reset-password", "/api/public/push-config", "/api/payments/webhooks/razorpay"}

def dependency_names(node):
    names = set()
    for arg in ast.walk(node):
        if isinstance(arg, ast.Call) and isinstance(arg.func, ast.Name) and arg.func.id == "Depends" and arg.args:
            dep = arg.args[0]
            if isinstance(dep, ast.Name): names.add(dep.id)
            elif isinstance(dep, ast.Attribute): names.add(dep.attr)
    return names

def main():
    routes = []
    for file in sorted(ROOT.glob("*.py")):
        tree = ast.parse(file.read_text(encoding="utf-8"), filename=str(file))
        for node in ast.walk(tree):
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            deps = dependency_names(node.args)
            for dec in node.decorator_list:
                if not isinstance(dec, ast.Call) or not isinstance(dec.func, ast.Attribute): continue
                if dec.func.attr not in ROUTE_METHODS: continue
                if not dec.args or not isinstance(dec.args[0], ast.Constant) or not isinstance(dec.args[0].value, str): continue
                path = dec.args[0].value
                method = dec.func.attr.upper()
                protected = bool(deps & AUTH_NAMES) or any(name.endswith("_only") for name in deps)
                if protected:
                    status = "PROTECTED — verify object/tenant authorization"
                elif path in PUBLIC_EXACT or path.startswith(PUBLIC_PATH_PREFIXES):
                    status = "PUBLIC — intentionally exposed; validate/rate-limit"
                else:
                    status = "REVIEW REQUIRED — no direct auth dependency detected"
                routes.append((file.name, node.lineno, method, path, node.name, ", ".join(sorted(deps)) or "—", status))
    routes.sort(key=lambda row: (row[3], row[2], row[0], row[1]))
    output = ["# Static API Route Security Inventory", "", "Generated by `scripts/security_route_inventory.py`. Static analysis only: indirect dependencies and runtime behavior require manual review.", "", f"Routes found: **{len(routes)}**", "", "| Method | Path | Handler | Dependencies | Static classification |", "|---|---|---|---|---|"]
    for file, line, method, path, handler, deps, status in routes:
        output.append(f"| `{method}` | `{path}` | `{handler}` (`{file}:{line}`) | `{deps}` | {status} |")
    target = Path(__file__).resolve().parents[1] / "docs" / "API_SECURITY_INVENTORY.md"
    target.write_text("\n".join(output) + "\n", encoding="utf-8")
    print(f"Wrote {target} with {len(routes)} route entries")
    print("Review-required routes:")
    for _, _, method, path, handler, deps, status in routes:
        if status.startswith("REVIEW REQUIRED"):
            print(f"  {method:7} {path:55} {handler} deps={deps}")

if __name__ == "__main__": main()
