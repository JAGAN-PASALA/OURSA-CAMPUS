import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";

test("build contains the product metadata and academic workspace", async () => {
  const server = await readFile(new URL("../dist/server/index.js", import.meta.url), "utf8");
  const page = await readFile(new URL("../app/page.tsx", import.meta.url), "utf8");
  const portal = await readFile(new URL("../app/portal-ui.tsx", import.meta.url), "utf8");
  const vite = await readFile(new URL("../vite.config.ts", import.meta.url), "utf8");
  assert.match(server, /OUR'S Smart Classroom/);
  assert.match(page, /Welcome to/);
  assert.match(page, /Institutions/);
  assert.match(page, /Academic plan/);
  assert.match(page, /Platform administration only/);
  assert.match(page, /Customer support access/);
  assert.match(page, /Validation and release governance/);
  assert.match(page, /Subject and teacher allocation/);
  assert.match(page, /College operations/);
  assert.match(page, /Create test draft/);
  assert.match(page, /Number of questions/);
  assert.match(page, /Show correct answers after submission/);
  assert.match(page, /Correct student details/);
  assert.match(page, /Correct department details/);
  assert.match(page, /Assign or move student/);
  assert.match(page, /Replace assigned teacher/);
  assert.match(page, /Post an assignment/);
  assert.match(page, /My coursework/);
  assert.match(page, /Student and staff face enrolment/);
  assert.match(page, /Face enrolment only \(no login\)/);
  assert.match(page, /Presence required/);
  assert.match(page, /Finalize class attendance/);
  assert.match(page, /Needs review \/ exception/);
  assert.match(page, /Authorized corrections remain available/);
  assert.match(page, /Replace logo/);
  assert.match(page, /Camera operations and room diagnostics/);
  assert.match(portal, /const API = "";/);
  const notifications = await readFile(new URL("../app/notification-center.tsx", import.meta.url), "utf8");
  assert.match(notifications, /Assignments & exams/);
  assert.match(notifications, /Notification categories/);
  assert.match(page, /Subject-wise analysis/);
  assert.doesNotMatch(page, /Assign later/);
  assert.doesNotMatch(page, /Model needs training/);
  assert.doesNotMatch(page, /model not trained/);
  assert.doesNotMatch(server, /codex-preview/);
  assert.match(page, /const API = "";/);
  assert.match(vite, /"\/api"/);
  assert.match(vite, /127\.0\.0\.1:8000/);
});
